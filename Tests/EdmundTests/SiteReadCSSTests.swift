import Testing
import Foundation
@testable import EdmundCore

// Regenerates site/src/styles/read.css, the website's copy of Read mode's
// light-theme CSS. Skipped unless EDMUND_SITE_READ_CSS names the output file:
//   EDMUND_SITE_READ_CSS=$PWD/site/src/styles/read.css swift test --filter SiteReadCSS

@Suite("Site read.css")
struct SiteReadCSSTests {

    @MainActor
    @Test("Write Read mode CSS for the site",
          .enabled(if: ProcessInfo.processInfo.environment["EDMUND_SITE_READ_CSS"] != nil))
    func write() throws {
        let path = ProcessInfo.processInfo.environment["EDMUND_SITE_READ_CSS"]!
        // The site always shows the Classic theme, whatever else is active.
        ThemeStore.shared.activeGeneralLight = "classic-light"
        let css = HTMLTheme.css(.default, callouts: Callout.defaultStyles, dark: false)
        let header = "/* Read mode CSS, Classic light theme. Generated by SiteReadCSSTests; do not edit. */\n"
        try (header + css).write(toFile: path, atomically: true, encoding: .utf8)
    }
}
